-- CRM-owned extensions only. No raw import or connector object is changed.
CREATE TABLE crm_customer_profiles (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id integer NOT NULL UNIQUE REFERENCES customers(id),
  state_code text CHECK(state_code IS NULL OR state_code ~ '^[0-9]{2}$'),
  payment_terms text,
  company_id uuid REFERENCES tally_companies(id), tally_ledger_name text,
  created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now(),
  created_by integer NOT NULL REFERENCES users(id),
  status text NOT NULL DEFAULT 'ACTIVE' CHECK(status IN ('ACTIVE','INACTIVE','ARCHIVED')),
  is_deleted boolean NOT NULL DEFAULT false,
  CHECK((company_id IS NULL)=(tally_ledger_name IS NULL))
);
CREATE TABLE crm_item_profiles (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  item_id integer NOT NULL UNIQUE REFERENCES items(id),
  moq numeric(20,6) NOT NULL DEFAULT 1 CHECK(moq>0),
  list_price numeric(20,6) NOT NULL DEFAULT 0 CHECK(list_price>=0),
  discount_percent numeric(9,6) NOT NULL DEFAULT 0 CHECK(discount_percent BETWEEN 0 AND 100),
  company_id uuid REFERENCES tally_companies(id), tally_stock_name text,
  created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now(),
  created_by integer NOT NULL REFERENCES users(id),
  status text NOT NULL DEFAULT 'ACTIVE' CHECK(status IN ('ACTIVE','INACTIVE','ARCHIVED')),
  is_deleted boolean NOT NULL DEFAULT false,
  CHECK((company_id IS NULL)=(tally_stock_name IS NULL))
);
CREATE TABLE crm_customer_part_mappings (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id integer NOT NULL REFERENCES customers(id), item_id integer NOT NULL REFERENCES items(id),
  customer_part_number text NOT NULL CHECK(length(trim(customer_part_number))>0),
  created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now(),
  created_by integer NOT NULL REFERENCES users(id),
  status text NOT NULL DEFAULT 'ACTIVE' CHECK(status IN ('ACTIVE','INACTIVE','ARCHIVED')),
  is_deleted boolean NOT NULL DEFAULT false,
  UNIQUE(customer_id,customer_part_number)
);
CREATE TABLE crm_price_lists (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL UNIQUE, currency text NOT NULL DEFAULT 'INR' CHECK(currency ~ '^[A-Z]{3}$'),
  effective_from date NOT NULL, effective_to date,
  discount_percent numeric(9,6) NOT NULL DEFAULT 0 CHECK(discount_percent BETWEEN 0 AND 100),
  created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now(),
  created_by integer NOT NULL REFERENCES users(id),
  status text NOT NULL DEFAULT 'ACTIVE' CHECK(status IN ('ACTIVE','INACTIVE','ARCHIVED')),
  is_deleted boolean NOT NULL DEFAULT false,
  CHECK(effective_to IS NULL OR effective_to>=effective_from)
);
CREATE TABLE crm_price_list_items (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  price_list_id bigint NOT NULL REFERENCES crm_price_lists(id), item_id integer NOT NULL REFERENCES items(id),
  unit_price numeric(20,6) NOT NULL CHECK(unit_price>=0),
  discount_percent numeric(9,6) NOT NULL DEFAULT 0 CHECK(discount_percent BETWEEN 0 AND 100),
  min_quantity numeric(20,6) NOT NULL DEFAULT 1 CHECK(min_quantity>0),
  created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now(),
  created_by integer NOT NULL REFERENCES users(id),
  status text NOT NULL DEFAULT 'ACTIVE' CHECK(status IN ('ACTIVE','INACTIVE','ARCHIVED')),
  is_deleted boolean NOT NULL DEFAULT false,
  UNIQUE(price_list_id,item_id,min_quantity)
);
CREATE INDEX crm_customer_profiles_link ON crm_customer_profiles(company_id,tally_ledger_name);
CREATE INDEX crm_item_profiles_link ON crm_item_profiles(company_id,tally_stock_name);
CREATE INDEX crm_customer_part_item ON crm_customer_part_mappings(customer_id,item_id);
CREATE INDEX crm_price_list_item_lookup ON crm_price_list_items(item_id,price_list_id);

-- Exact-name, ambiguity-aware read mappings. No write-through views.
CREATE VIEW crm_customer_tally_facts AS
SELECT p.customer_id,p.company_id,p.tally_ledger_name,count(l.id) AS match_count,
  CASE WHEN count(l.id)=1 THEN min(l.closing_balance)::text END AS closing_balance,
  CASE WHEN count(l.id)=1 THEN min(l.dr_cr) END AS dr_cr,
  CASE WHEN count(l.id)=1 THEN max(l.fetched_at) END AS fetched_at
FROM crm_customer_profiles p LEFT JOIN tally_ledgers l
  ON l.company_id=p.company_id AND l.name=p.tally_ledger_name
WHERE p.status='ACTIVE' AND NOT p.is_deleted GROUP BY p.customer_id,p.company_id,p.tally_ledger_name;
CREATE VIEW crm_item_tally_facts AS
SELECT p.item_id,p.company_id,p.tally_stock_name,count(s.id) AS match_count,
  CASE WHEN count(s.id)=1 THEN min(s.closing_quantity_text) END AS quantity,
  CASE WHEN count(s.id)=1 THEN min(s.closing_rate_text) END AS rate,
  CASE WHEN count(s.id)=1 THEN min(s.closing_value)::text END AS value,
  CASE WHEN count(s.id)=1 THEN max(s.fetched_at) END AS fetched_at
FROM crm_item_profiles p LEFT JOIN tally_stock_items s
  ON s.company_id=p.company_id AND s.name=p.tally_stock_name
WHERE p.status='ACTIVE' AND NOT p.is_deleted GROUP BY p.item_id,p.company_id,p.tally_stock_name;

CREATE FUNCTION crm_module_audit_guard() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE actor integer; reason text;
BEGIN
  IF TG_OP IN ('DELETE','TRUNCATE') THEN RAISE EXCEPTION 'Archive CRM records with a reason instead'; END IF;
  actor:=NULLIF(current_setting('mehta.actor_id',true),'')::integer;
  reason:=NULLIF(current_setting('mehta.audit_reason',true),'');
  IF actor IS NULL THEN RAISE EXCEPTION 'An audit actor is required'; END IF;
  IF TG_OP='UPDATE' THEN
    IF reason IS NULL THEN RAISE EXCEPTION 'An edit reason is required'; END IF;
    NEW.updated_at:=now();
  ELSIF NEW.created_by IS DISTINCT FROM actor THEN RAISE EXCEPTION 'Creator must match audit actor';
  END IF;
  IF NEW.is_deleted AND NEW.status<>'ARCHIVED' THEN RAISE EXCEPTION 'Soft deletion requires ARCHIVED status'; END IF;
  INSERT INTO audit_logs(user_id,entity,record_id,action,old_value,new_value,reason)
  VALUES(actor,TG_TABLE_NAME,NEW.id::text,TG_OP,CASE WHEN TG_OP='UPDATE' THEN row_to_json(OLD)::text END,row_to_json(NEW)::text,reason);
  RETURN NEW;
END;
$$;
DO $$ DECLARE t text; BEGIN
  FOREACH t IN ARRAY ARRAY['crm_customer_profiles','crm_item_profiles','crm_customer_part_mappings','crm_price_lists','crm_price_list_items'] LOOP
    EXECUTE format('CREATE TRIGGER crm_module_audit BEFORE INSERT OR UPDATE OR DELETE ON %I FOR EACH ROW EXECUTE FUNCTION crm_module_audit_guard()',t);
    EXECUTE format('CREATE TRIGGER crm_module_no_truncate BEFORE TRUNCATE ON %I FOR EACH STATEMENT EXECUTE FUNCTION crm_module_audit_guard()',t);
  END LOOP;
END $$;
