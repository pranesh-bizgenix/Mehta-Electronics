-- Additive CRM-owned metadata only. Imported tables and connector contracts are untouched.
CREATE TABLE crm_parties (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id uuid NOT NULL REFERENCES tally_companies(id),
  name text NOT NULL,
  party_role text NOT NULL CHECK (party_role IN ('CUSTOMER','VENDOR')),
  customer_id integer REFERENCES customers(id),
  phone text, email text, gstin text, address text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  created_by integer NOT NULL REFERENCES users(id),
  status text NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','INACTIVE','ARCHIVED')),
  is_deleted boolean NOT NULL DEFAULT false,
  archive_reason text,
  CHECK (NOT is_deleted OR (status='ARCHIVED' AND length(trim(archive_reason))>0)),
  UNIQUE(company_id,name,party_role)
);
CREATE TABLE crm_tally_item_links (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id uuid NOT NULL REFERENCES tally_companies(id),
  item_id integer NOT NULL REFERENCES items(id),
  tally_name text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  created_by integer NOT NULL REFERENCES users(id),
  status text NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','INACTIVE','ARCHIVED')),
  is_deleted boolean NOT NULL DEFAULT false,
  archive_reason text,
  CHECK (NOT is_deleted OR (status='ARCHIVED' AND length(trim(archive_reason))>0)),
  UNIQUE(company_id,tally_name), UNIQUE(company_id,item_id)
);
CREATE FUNCTION crm_read_metadata_guard() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE actor integer; reason text;
BEGIN
  IF TG_OP IN ('DELETE','TRUNCATE') THEN
    RAISE EXCEPTION 'Archive CRM read-layer metadata with an audit reason instead';
  END IF;
  actor := NULLIF(current_setting('mehta.actor_id',true),'')::integer;
  IF actor IS NULL THEN RAISE EXCEPTION 'CRM metadata requires an audit actor'; END IF;
  reason := NULLIF(current_setting('mehta.audit_reason',true),'');
  IF TG_OP='UPDATE' THEN
    IF (NEW.status IS DISTINCT FROM OLD.status OR NEW.is_deleted IS DISTINCT FROM OLD.is_deleted) AND reason IS NULL THEN
      RAISE EXCEPTION 'Status changes require an audit reason';
    END IF;
    NEW.updated_at := now();
  END IF;
  INSERT INTO audit_logs(user_id,entity,record_id,action,old_value,new_value,reason)
  VALUES(actor,TG_TABLE_NAME,NEW.id::text,TG_OP,
    CASE WHEN TG_OP='UPDATE' THEN row_to_json(OLD)::text ELSE NULL END,row_to_json(NEW)::text,reason);
  RETURN NEW;
END;
$$;
CREATE TRIGGER crm_parties_audited BEFORE INSERT OR UPDATE OR DELETE ON crm_parties
FOR EACH ROW EXECUTE FUNCTION crm_read_metadata_guard();
CREATE TRIGGER crm_parties_no_truncate BEFORE TRUNCATE ON crm_parties
FOR EACH STATEMENT EXECUTE FUNCTION crm_read_metadata_guard();
CREATE TRIGGER crm_tally_item_links_audited BEFORE INSERT OR UPDATE OR DELETE ON crm_tally_item_links
FOR EACH ROW EXECUTE FUNCTION crm_read_metadata_guard();
CREATE TRIGGER crm_tally_item_links_no_truncate BEFORE TRUNCATE ON crm_tally_item_links
FOR EACH STATEMENT EXECUTE FUNCTION crm_read_metadata_guard();

-- Non-updatable aggregate views: these expose source facts without adding write paths.
CREATE VIEW crm_tally_stock_coverage AS
SELECT company_id, count(*) AS total_items, count(closing_value) AS valued_items,
  count(*) FILTER (WHERE closing_value IS NULL) AS missing_value_items,
  count(*) FILTER (WHERE closing_value<0) AS negative_value_items,
  sum(closing_value)::text AS signed_known_value,
  CASE WHEN count(*)>0 AND count(closing_value)=count(*) THEN sum(closing_value)::text END AS complete_signed_value
FROM tally_stock_items GROUP BY company_id;
